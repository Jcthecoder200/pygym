"""pygym: micro-exercises for Python built-ins."""
from . import tips
from .loader import ExerciseUnavailable, available_functions

__version__ = "0.3.1"
__all__ = ["exercise", "available_functions", "ExerciseUnavailable", "Session", "tips"]


def __getattr__(name):
    # `pygym.Session` is imported on first use: the session module brings the grader and the
    # sandbox (subprocess, tempfile, ...), which `import pygym` and the tips under a traceback
    # do not need.
    if name == "Session":
        from .session import Session
        globals()["Session"] = Session
        return Session
    raise AttributeError(f"module 'pygym' has no attribute {name!r}")


def exercise(name, difficulty=None, ui="auto", mode=None):
    """Start an exercise. `name` is a built-in's name (or the function itself).

    `mode` is "preset" (bundled exercises, offline) or "ai" (generated by a local LLM; falls back to
    preset when that fails). None = the saved setting (see `pygym.config`).

    `difficulty` is the starting level 1, 2 or 3 (None = 1). After 3 exercises solved at a level
    the next one is a level higher; `:level` shows or changes it. A function too small for an
    advanced exercise on its own (`bin`, `abs`) starts at intermediate and asks first whether to
    practise it inside a bigger task (generated exercises only). `ui` chooses the front-end:
      "auto"     (default) Jupyter notebook -> "jupyter"; Linux/macOS terminal -> "editor";
                 otherwise "tk" if a window can open, else "text"
      "jupyter"  write code in notebook cells that start with  %%pygym :w
      "editor"   full-screen terminal editor (Neovim-like: i to type, Esc, then :w / :wq / :q)
      "tk"       a small tkinter window
      "text"     the line-by-line CLI (works everywhere, also on Windows)
    """
    from . import ui as _ui
    from .session import Session

    if callable(name):
        name = getattr(name, "__name__", str(name))
    try:
        session = Session(name, difficulty, mode=mode)
    except ExerciseUnavailable as e:
        print(e)
        return
    _ui.run(session, ui)


def load_ipython_extension(ipython):
    """`%load_ext pygym`: tips under the tracebacks of this IPython session (pygym.tips)."""
    tips.set_tips(True, shell=ipython, quiet=True)


def unload_ipython_extension(ipython):
    """`%unload_ext pygym`: no more tips in this session."""
    tips.set_tips(False, shell=ipython, quiet=True)


# Tips at your error: on for this process unless the saved setting `tips` is off.
